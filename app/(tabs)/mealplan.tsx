/**
 * @fileoverview Meal Plan Screen - week strip with photo cards per meal, AI plan generation and shopping hand-off.
 *
 * Design: MealPlan.html (+ PlanGenerator.html as a full-screen modal). Logic is unchanged: auto-generation on
 * first visit, expiring-ingredient prioritisation, Pro gating on generation, premium gating on viewing.
 *
 * @module app/(tabs)/mealplan
 */

import React, { useState, useEffect, useRef } from 'react';
import { Alert, Pressable, ScrollView, View } from 'react-native';
import { useRouter, type Href } from 'expo-router';
import { useTranslation } from 'react-i18next';
import { useMealPlan, useMealPlanStats } from '@/hooks/useMealPlan';
import { usePantryStore } from '@/stores/pantryStore';
import { useRecipeStore } from '@/stores/recipeStore';
import { useAuthStore } from '@/stores/authStore';
import { WeekView, PlanGenerator, SavingsDisplay } from '@/components/mealplan';
import { Loading } from '@/components/ui/Loading';
import {
  Body,
  H2,
  Icon,
  LinkText,
  Muted,
  Screen,
  Tag,
  TopBar,
  UButton,
  UIconButton,
} from '@/components/ui';
import { Paywall } from '@/components/subscription';
import { getWeekStartDate } from '@/services/mealPlanService';
import { MealPlanPreferences, MealType } from '@/types/mealplan';
import { showSuccessToast, showInfoToast } from '@/stores/toastStore';

export default function MealPlanScreen() {
  const router = useRouter();
  const { t } = useTranslation();
  const { getExpiringItems, getExpiredItems } = usePantryStore();
  const { recipes } = useRecipeStore();
  const { user } = useAuthStore();
  const hasAutoGenerated = useRef(false);

  const {
    currentPlan,
    isLoading,
    isGenerating,
    error,
    selectedWeekStart,
    canView,
    canGenerate,
    generate,
    clear,
    goToWeek,
    updatePreferences,
    removeMeal,
    save,
  } = useMealPlan();

  const stats = useMealPlanStats();

  const [showGenerator, setShowGenerator] = useState(false);
  const [showPaywall, setShowPaywall] = useState(false);

  // Expiring and expired pantry items: surfaced in the generator and prioritised by the AI.
  const expiringItems = React.useMemo(
    () => [...getExpiringItems(), ...getExpiredItems()],
    [getExpiringItems, getExpiredItems]
  );
  const isCurrentWeek = selectedWeekStart === getWeekStartDate();

  // Auto-generate a plan on first visit when none exists (Pro, has recipes, current week).
  useEffect(() => {
    if (
      !isLoading &&
      !currentPlan &&
      !hasAutoGenerated.current &&
      canGenerate.allowed &&
      recipes.length > 0 &&
      isCurrentWeek
    ) {
      hasAutoGenerated.current = true;
      updatePreferences({
        servingsPerMeal: 2,
        daysToGenerate: 7,
        mealsToInclude: ['breakfast', 'lunch', 'dinner'] as MealType[],
        dietaryRestrictions: [
          ...(user?.dietaryPreferences || []),
          ...(user?.allergies?.map((a) => `no ${a}`) || []),
        ],
        healthConditions: user?.healthConditions || [],
        cuisinePreferences: [],
        prioritizeExpiring: true,
        maximizeOverlap: true,
        budgetFriendly: true,
      });
      const timeoutId = setTimeout(() => {
        generate();
        showInfoToast(
          t('plan.autoGenBody', 'AI is creating your personalized meal plan.'),
          t('plan.autoGenTitle', 'Generating Plan')
        );
      }, 500);
      return () => clearTimeout(timeoutId);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [isLoading, currentPlan, canGenerate.allowed, recipes.length, isCurrentWeek, user]);

  const shiftWeek = (days: number) => {
    const d = new Date(selectedWeekStart);
    d.setDate(d.getDate() + days);
    goToWeek(d.toISOString().split('T')[0]);
  };

  const handleMealPress = (_date: string, _mealType: MealType, recipeId?: string) => {
    if (recipeId) {
      router.push(`/recipe/${recipeId}`);
    }
  };

  // Empty slot or swap: pick a recipe from the browser in meal-selection mode.
  const handleAddMeal = (date: string, mealType: MealType) => {
    router.push({
      pathname: '/browse',
      params: { selectForMeal: mealType, date },
    });
  };

  const handleRemoveMeal = (date: string, mealType: MealType) => {
    Alert.alert(
      t('plan.removeTitle', 'Remove Meal'),
      t('plan.removeBody', 'Remove this meal from your plan?'),
      [
        { text: t('common.cancel', 'Cancel'), style: 'cancel' },
        {
          text: t('plan.remove', 'Remove'),
          style: 'destructive',
          onPress: async () => {
            removeMeal(date, mealType);
            await save();
            showSuccessToast(t('plan.removedBody', 'Meal removed from plan'), t('plan.updated', 'Updated'));
          },
        },
      ]
    );
  };

  const handleGenerate = async () => {
    if (!canGenerate.allowed) {
      setShowPaywall(true);
      return;
    }
    if (recipes.length === 0) {
      Alert.alert(
        t('plan.noRecipesTitle', 'No Recipes'),
        t('plan.noRecipesBody', 'Add some recipes first to generate a meal plan.'),
        [{ text: t('common.ok', 'OK') }]
      );
      return;
    }
    setShowGenerator(true);
  };

  const handleGenerateConfirm = async (preferences: MealPlanPreferences) => {
    updatePreferences(preferences);
    setShowGenerator(false);
    await generate();
  };

  const handleClearPlan = () => {
    Alert.alert(
      t('plan.clearTitle', 'Clear Meal Plan'),
      t('plan.clearBody', "Are you sure you want to clear this week's meal plan?"),
      [
        { text: t('common.cancel', 'Cancel'), style: 'cancel' },
        { text: t('plan.clear', 'Clear'), style: 'destructive', onPress: () => clear() },
      ]
    );
  };

  const handleFinalizePlan = async () => {
    if (!currentPlan) return;
    Alert.alert(
      t('plan.finalizeTitle', 'Finalize Meal Plan'),
      t('plan.finalizeBody', 'Your meal plan looks great! This will save your plan and mark it as complete.'),
      [
        { text: t('plan.keepEditing', 'Keep Editing'), style: 'cancel' },
        {
          text: t('plan.finalize', 'Finalize'),
          onPress: async () => {
            await save();
            showSuccessToast(
              t('plan.finalizedBody', 'Your meal plan is ready! Check out your shopping list.'),
              t('plan.finalizedTitle', 'Plan Finalized')
            );
          },
        },
      ]
    );
  };

  const openShopping = () => router.push('/mealplan/shopping' as Href);
  const openWaste = () => router.push('/mealplan/waste' as Href);

  // Free users: premium gate.
  if (!canView) {
    return (
      <Screen bare>
        <TopBar title={t('plan.title', 'Meal Plan')} />
        <View className="flex-1 items-center justify-center" style={{ paddingHorizontal: 32, gap: 16 }}>
          <View className="items-center justify-center bg-surface-2" style={{ width: 80, height: 80, borderRadius: 40 }}>
            <Icon name="clock" size="lg" />
          </View>
          <H2 center>{t('plan.gateTitle', 'Meal Planning')}</H2>
          <Muted center>
            {t(
              'plan.gateBody',
              'Plan your meals for the week, reduce food waste, and save money with smart shopping lists.'
            )}
          </Muted>
          <View style={{ alignSelf: 'stretch' }}>
            <UButton
              variant="accent"
              icon="star"
              label={t('plan.upgrade', 'Upgrade to Premium')}
              onPress={() => setShowPaywall(true)}
            />
          </View>
        </View>
        <Paywall
          visible={showPaywall}
          onClose={() => setShowPaywall(false)}
          feature="Meal Planning"
          requiredTier="premium"
        />
      </Screen>
    );
  }

  if (isLoading) {
    return <Loading fullScreen message={t('plan.loading', 'Loading meal plan...')} />;
  }

  const unchecked = currentPlan ? currentPlan.shoppingList.filter((i) => !i.checked).length : 0;

  return (
    <Screen bare>
      <TopBar
        title={t('plan.title', 'Meal Plan')}
        right={
          <View className="flex-row" style={{ gap: 8 }}>
            <UIconButton icon="leaf" label={t('plan.wasteTracking', 'Waste tracking')} onPress={openWaste} />
            <UIconButton
              icon="refresh"
              tone="black"
              label={t('plan.generatePlan', 'Generate plan')}
              onPress={handleGenerate}
            />
          </View>
        }
      />

      <ScrollView
        contentContainerStyle={{ paddingHorizontal: 20, gap: 14, paddingBottom: 130 }}
        showsVerticalScrollIndicator={false}
      >
        {error ? (
          <View className="bg-tag-r" style={{ borderRadius: 20, padding: 14 }}>
            <Body className="text-tag-r-fg">{error}</Body>
          </View>
        ) : null}

        {currentPlan && stats.estimatedSavings > 0 ? (
          <SavingsDisplay savedByPlanning={stats.estimatedSavings} expiringItemsUsed={stats.expiringItemsUsed} />
        ) : null}

        {currentPlan ? (
          <>
            <WeekView
              days={currentPlan.days}
              selectedWeekStart={selectedWeekStart}
              onPreviousWeek={() => shiftWeek(-7)}
              onNextWeek={() => shiftWeek(7)}
              onMealPress={handleMealPress}
              onAddMeal={handleAddMeal}
              onRemoveMeal={handleRemoveMeal}
              isCurrentWeek={isCurrentWeek}
            />

            <Pressable
              accessibilityRole="button"
              accessibilityLabel={t('plan.shoppingList', 'Shopping list')}
              onPress={openShopping}
              className="flex-row items-center justify-between"
              style={{ minHeight: 50, gap: 12 }}
            >
              <Muted style={{ flexShrink: 1 }}>
                {t('plan.summary', '{{meals}} meals · {{pct}}% ingredient overlap', {
                  meals: stats.totalMeals,
                  pct: stats.ingredientOverlap,
                })}
              </Muted>
              <LinkText className="text-ink">
                {unchecked > 0
                  ? t('plan.shoppingLinkN', 'Shopping list ({{n}}) →', { n: unchecked })
                  : t('plan.shoppingLink', 'Shopping list →')}
              </LinkText>
            </Pressable>

            {isCurrentWeek && stats.totalMeals > 0 ? (
              <UButton
                label={t('plan.finalizeCta', 'Finalize & View Shopping List')}
                onPress={handleFinalizePlan}
              />
            ) : null}

            <Pressable
              accessibilityRole="button"
              accessibilityLabel={t('plan.reset', 'Reset')}
              onPress={handleClearPlan}
              className="flex-row items-center justify-center"
              style={{ minHeight: 44, gap: 6 }}
            >
              <Icon name="refresh" size="sm" color="muted" />
              <LinkText>{t('plan.reset', 'Reset')}</LinkText>
            </Pressable>
          </>
        ) : (
          <View className="items-center" style={{ paddingTop: 48, paddingHorizontal: 12, gap: 16 }}>
            <View className="items-center justify-center bg-surface-2" style={{ width: 96, height: 96, borderRadius: 48 }}>
              <Icon name="kitchen" size="lg" color="muted" />
            </View>
            <H2 center>{t('plan.emptyTitle', 'No Meal Plan Yet')}</H2>
            <Muted center>
              {t('plan.emptyBody', 'Generate an AI-optimized meal plan based on your pantry and preferences.')}
            </Muted>
            {expiringItems.length > 0 ? (
              <Tag
                tone="o"
                icon="warning"
                label={t('plan.expiringSoon', '{{n}} items expiring soon', { n: expiringItems.length })}
              />
            ) : null}
            <View style={{ alignSelf: 'stretch' }}>
              <UButton
                variant="accent"
                icon={canGenerate.allowed ? undefined : 'lock'}
                label={
                  canGenerate.allowed
                    ? t('plan.generate', 'Generate Meal Plan')
                    : t('plan.upgradeToGenerate', 'Upgrade to Generate')
                }
                onPress={handleGenerate}
              />
            </View>
            {!canGenerate.allowed ? (
              <Muted small center>
                {t('plan.proRequired', 'Pro subscription required for AI generation')}
              </Muted>
            ) : null}
          </View>
        )}
      </ScrollView>

      <PlanGenerator
        visible={showGenerator}
        onClose={() => setShowGenerator(false)}
        onGenerate={handleGenerateConfirm}
        isGenerating={isGenerating}
        expiringItemsCount={expiringItems.length}
        userDietaryPreferences={user?.dietaryPreferences}
        userAllergies={user?.allergies}
        onEditDietary={() => {
          setShowGenerator(false);
          router.push('/settings/dietary' as Href);
        }}
      />

      <Paywall
        visible={showPaywall}
        onClose={() => setShowPaywall(false)}
        feature="AI Meal Plan Generation"
        requiredTier="pro"
      />
    </Screen>
  );
}
